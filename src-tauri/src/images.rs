//! Portraits and reference images.
//!
//! Images live as ordinary files in `%APPDATA%\jjk-rp-vault\images\`, and a record stores only
//! the file name. Two reasons for that over inlining the picture in the JSON:
//!
//!   * a vault file stays something Dan can open and read (CLAUDE.md §1), rather than a line
//!     of base64 a megabyte wide;
//!   * the same picture can be reused by several records without being stored twice.
//!
//! Reading hands the frontend a `data:` URL. That avoids registering Tauri's asset protocol and
//! loosening the webview's CSP just to show a portrait — the bytes never leave the machine
//! either way, and the frontend already has the image in memory when it uploads one.
//!
//! The frontend downscales before sending (see `services/images.ts`), so the files here are
//! small by the time Rust sees them.

use std::fs;
use std::path::PathBuf;

use tauri::AppHandle;

use crate::vault::app_root;

/// Generous for a downscaled portrait, tight enough that a stray 40MB TIFF is refused.
const MAX_BYTES: usize = 8 * 1024 * 1024;
const MAX_NAME_LEN: usize = 80;

/// Extension -> media type. The whitelist is the format check: anything else is refused.
fn media_type(ext: &str) -> Result<&'static str, String> {
    match ext {
        "png" => Ok("image/png"),
        "jpg" | "jpeg" => Ok("image/jpeg"),
        "webp" => Ok("image/webp"),
        "gif" => Ok("image/gif"),
        other => Err(format!("Unsupported image type: {other}")),
    }
}

fn images_dir(app: &AppHandle) -> Result<PathBuf, String> {
    let dir = app_root(app)?.join("images");
    fs::create_dir_all(&dir).map_err(|e| format!("Could not create {}: {e}", dir.display()))?;
    Ok(dir)
}

/// File names are generated by the app, never typed, so this is a whitelist rather than a
/// sanitiser — and it is what stops a crafted record reading a file elsewhere on the disk.
fn validate_name(name: &str) -> Result<&'static str, String> {
    if name.is_empty() || name.len() > MAX_NAME_LEN {
        return Err("Image name must be between 1 and 80 characters".to_string());
    }

    let Some((stem, ext)) = name.rsplit_once('.') else {
        return Err("Image name must have an extension".to_string());
    };

    if stem.is_empty()
        || !stem
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
    {
        return Err("Image name may only contain letters, digits, hyphens and underscores".into());
    }

    media_type(ext)
}

/// Minimal RFC 4648 base64. Hand-rolled rather than pulling in a crate for twenty lines
/// (CLAUDE.md §10 — ask before adding a dependency).
fn base64(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] =
        b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);

    for chunk in bytes.chunks(3) {
        let b0 = chunk[0] as u32;
        let b1 = *chunk.get(1).unwrap_or(&0) as u32;
        let b2 = *chunk.get(2).unwrap_or(&0) as u32;
        let triple = (b0 << 16) | (b1 << 8) | b2;

        out.push(ALPHABET[(triple >> 18) as usize & 63] as char);
        out.push(ALPHABET[(triple >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 {
            ALPHABET[(triple >> 6) as usize & 63] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            ALPHABET[triple as usize & 63] as char
        } else {
            '='
        });
    }

    out
}

/// Store an image and return the file name to put in the record.
///
/// `bytes` arrives as a plain array over the IPC bridge; the frontend has already downscaled
/// and re-encoded it, so this is the final file.
pub fn save(app: &AppHandle, id: &str, ext: &str, bytes: Vec<u8>) -> Result<String, String> {
    let lowered = ext.to_ascii_lowercase();
    media_type(&lowered)?;

    if bytes.is_empty() {
        return Err("That image is empty".to_string());
    }
    if bytes.len() > MAX_BYTES {
        return Err(format!(
            "That image is {} MB; the limit is {} MB",
            bytes.len() / (1024 * 1024),
            MAX_BYTES / (1024 * 1024)
        ));
    }

    let name = format!("{id}.{lowered}");
    validate_name(&name)?;

    let path = images_dir(app)?.join(&name);
    fs::write(&path, &bytes).map_err(|e| format!("Could not write {}: {e}", path.display()))?;
    Ok(name)
}

/// Read an image back as a `data:` URL. A missing file is an error the UI shows in place of the
/// picture, never a crash — someone may well have deleted it from the folder by hand.
pub fn load(app: &AppHandle, name: &str) -> Result<String, String> {
    let mime = validate_name(name)?;
    let path = images_dir(app)?.join(name);

    let bytes = fs::read(&path).map_err(|e| format!("Could not read {name}: {e}"))?;
    Ok(format!("data:{mime};base64,{}", base64(&bytes)))
}

/// Remove an image. Already gone counts as success — the caller wanted it absent.
pub fn delete(app: &AppHandle, name: &str) -> Result<(), String> {
    validate_name(name)?;
    let path = images_dir(app)?.join(name);
    match fs::remove_file(&path) {
        Ok(()) => Ok(()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(e) => Err(format!("Could not delete {name}: {e}")),
    }
}

/// Every picture file name in the images folder.
///
/// Only the names — the bytes are read one at a time by `load`. Used by the problems panel to
/// tell a record pointing at a deleted picture from one that simply has none, which needs the
/// whole set rather than a base64 round-trip per record.
///
/// An unreadable entry is skipped rather than failing the listing: a folder the user can open
/// in Explorer may well contain something odd, and that is not a reason to report nothing.
pub fn list(app: &AppHandle) -> Result<Vec<String>, String> {
    let dir = images_dir(app)?;
    let entries =
        fs::read_dir(&dir).map_err(|e| format!("Could not read {}: {e}", dir.display()))?;

    let mut names: Vec<String> = entries
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().is_file())
        .filter_map(|entry| entry.file_name().to_str().map(|name| name.to_string()))
        .collect();

    names.sort();
    Ok(names)
}

pub fn reveal(app: &AppHandle) -> Result<(), String> {
    let dir = images_dir(app)?;
    crate::vault::open_in_explorer(&dir)
}

#[cfg(test)]
mod tests {
    use super::{base64, media_type, validate_name};

    #[test]
    fn base64_matches_the_rfc_test_vectors() {
        assert_eq!(base64(b""), "");
        assert_eq!(base64(b"f"), "Zg==");
        assert_eq!(base64(b"fo"), "Zm8=");
        assert_eq!(base64(b"foo"), "Zm9v");
        assert_eq!(base64(b"foob"), "Zm9vYg==");
        assert_eq!(base64(b"fooba"), "Zm9vYmE=");
        assert_eq!(base64(b"foobar"), "Zm9vYmFy");
    }

    #[test]
    fn base64_handles_bytes_above_ascii() {
        assert_eq!(base64(&[0xff, 0xfe, 0xfd]), "//79");
        assert_eq!(base64(&[0x00, 0x00, 0x00]), "AAAA");
    }

    #[test]
    fn names_are_whitelisted_not_sanitised() {
        assert!(validate_name("abc123.png").is_ok());
        assert!(validate_name("a-b_c.jpg").is_ok());

        assert!(validate_name("../secret.png").is_err());
        assert!(validate_name("sub/dir.png").is_err());
        assert!(validate_name("sub\\dir.png").is_err());
        assert!(validate_name("no-extension").is_err());
        assert!(validate_name(".png").is_err());
        assert!(validate_name("good.exe").is_err());
        assert!(validate_name("").is_err());
    }

    #[test]
    fn only_image_types_are_accepted() {
        assert!(media_type("png").is_ok());
        assert!(media_type("jpeg").is_ok());
        assert!(media_type("svg").is_err());
        assert!(media_type("PNG").is_err(), "callers lowercase before asking");
    }
}
